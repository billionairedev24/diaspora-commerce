/* Server-only by construction (next/headers, the gateway client); no `server-only` import so the page tests can load it. */
import { createApiClient } from '@afrotransact/api-client';
import { getTelemetry } from '@afrotransact/telemetry';
import { headers } from 'next/headers';

import { bffOrigin, mocksEnabled } from '../config';
import { type IndexingPolicy, indexingPolicy, seoEnvFromProcess, sitemapOrigin } from './policy';
import { createSitemapCache, type SeoEvent, type SitemapCache } from './sitemap-cache';
import { buildSitemapSet, type SeoApi } from './sitemap-source';

/** The indexing decision of the current request (server components and metadata). */
export async function getIndexingPolicy(): Promise<IndexingPolicy> {
  const h = await headers();
  return indexingPolicy(seoEnvFromProcess(), h.get('host'));
}

/** The decision for a Request (route handlers). */
export function policyForRequest(req: Request): IndexingPolicy {
  return indexingPolicy(seoEnvFromProcess(), req.headers.get('host') ?? new URL(req.url).host);
}

/** The origin the sitemap routes serve for this request (prod host, or a local run's loopback origin); undefined means 404. */
export function sitemapOriginForRequest(req: Request): string | undefined {
  const url = new URL(req.url);
  return sitemapOrigin(seoEnvFromProcess(), req.headers.get('host') ?? url.host, url.protocol);
}

/** An anonymous gateway client: crawler-facing generation never forwards a shopper's cookies or location. */
async function anonymousApi(): Promise<SeoApi> {
  if (mocksEnabled()) {
    const { handleMockRequest } = await import('@afrotransact/api-client/mocks/runtime');
    return createApiClient({ baseUrl: 'http://storefront.internal/api/bff', fetch: (req) => handleMockRequest(req) });
  }
  return createApiClient({ baseUrl: bffOrigin(), fetch: (req) => fetch(req, { cache: 'no-store' }) });
}

/** Structured log line (Workers observability / Loki) plus a Sentry message for the events that need a human. */
function reportSeoEvent(e: SeoEvent): void {
  console.log(JSON.stringify({ level: e.event === 'sitemap.generated' ? 'info' : 'warn', ...e }));
  if (e.event !== 'sitemap.generated') getTelemetry().captureMessage(`seo ${e.event}`, { level: 'warning', tags: { seo_event: e.event, sitemap_kind: e.kind } });
}

/** Sitemaps older than this are regenerated by the next request (the scheduled regeneration). */
export const SITEMAP_TTL_MS = 15 * 60 * 1000;

const caches = new Map<string, SitemapCache>();

/** The sitemap cache of one canonical origin (one per Worker isolate). */
export function sitemapCache(origin: string): SitemapCache {
  let c = caches.get(origin);
  if (!c) {
    c = createSitemapCache({ ttlMs: SITEMAP_TTL_MS, report: reportSeoEvent, build: async () => buildSitemapSet(await anonymousApi(), origin) });
    caches.set(origin, c);
  }
  return c;
}
