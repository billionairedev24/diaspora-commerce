/**
 * The service worker, generated as JavaScript source from a typed config (so every app serves the same, tested rules).
 *
 * What it does, and nothing else:
 *  - precaches ONE offline page and shows it when a page navigation fails (no network);
 *  - serves immutable, public static assets (content-hashed build output, icons, the logo) cache-first, in a versioned
 *    cache that is trimmed to a maximum number of entries and cleaned up when the version changes.
 *
 * What it never does: cache or touch an API call, an auth route, the cart, checkout, orders, account pages, a React
 * Server Components payload or any HTML page. Anything it does not recognise goes straight to the network, as if no
 * service worker were installed. The rules are written for the worst case (a shared phone, a signed-in customer): a
 * page or response that may differ per person is never stored.
 */

export interface ServiceWorkerConfig {
  /** Cache name prefix, e.g. "afrotransact-storefront". Caches with this prefix but another version are deleted. */
  cachePrefix: string;
  /** Bump to purge every cache this worker created. Part of the generated source, so a change also updates the worker. */
  version: string;
  /** Same-origin path of the offline page, precached at install. */
  offlineUrl: string;
  /** Path prefixes that are never served from or stored in a cache (the worker does not even intercept them). */
  neverCache: readonly string[];
  /** Path prefixes of immutable public static assets (cache-first). */
  staticPrefixes: readonly string[];
  /** Exact paths of public static assets (cache-first). */
  staticFiles: readonly string[];
  /** Entry limit of the static cache; the oldest entries go first. */
  maxStaticEntries: number;
}

/** Cache layout version; bump when the cache rules change so old caches are cleaned up. */
export const PWA_CACHE_VERSION = '1';

/** Path prefixes no web app may ever cache: APIs, sign-in/out, cart, checkout, orders and every account-bound page. */
export const COMMON_NEVER_CACHE: readonly string[] = [
  '/api',
  '/bff',
  '/auth',
  '/sign-in',
  '/sign-up',
  '/signin',
  '/signup',
  '/login',
  '/logout',
  '/account',
  '/cart',
  '/checkout',
  '/orders',
  '/membership',
  '/back-office',
  '/sell',
  '/provide',
  '/_next/data',
  '/_next/image'
];

/** The service worker script's headers: never cached for long (browsers also cap it at 24 h), served as JavaScript. */
export const SERVICE_WORKER_HEADERS: Readonly<Record<string, string>> = {
  'Content-Type': 'text/javascript; charset=utf-8',
  'Cache-Control': 'no-cache, max-age=0, must-revalidate',
  'Service-Worker-Allowed': '/'
};

export const SERVICE_WORKER_PATH = '/sw.js';

/** The worker as source text. The body below is plain ES5-style JavaScript: it runs in a worker, not through the bundler. */
export function serviceWorkerSource(config: ServiceWorkerConfig): string {
  return `/* Generated by @afrotransact/pwa. Static assets only; never API, auth, cart, checkout or personalised responses. */
'use strict';
var CONFIG = ${JSON.stringify(config)};
var STATIC_CACHE = CONFIG.cachePrefix + '-static-' + CONFIG.version;
var OFFLINE_CACHE = CONFIG.cachePrefix + '-offline-' + CONFIG.version;

function startsWithPath(path, prefix) {
  return path === prefix || path.indexOf(prefix + '/') === 0;
}

/** True for anything that may be personal or live: never intercepted. */
function isNeverCached(url, request) {
  for (var i = 0; i < CONFIG.neverCache.length; i++) {
    if (startsWithPath(url.pathname, CONFIG.neverCache[i])) return true;
  }
  // Next.js App Router data requests (React Server Components payloads) are per-person pages in another format.
  if (url.searchParams.has('_rsc')) return true;
  var h = request.headers;
  if (h.get('RSC') || h.get('Next-Router-State-Tree') || h.get('Next-Router-Prefetch') || h.get('Next-Url')) return true;
  if (h.get('Authorization')) return true;
  return false;
}

function isStaticAsset(url) {
  if (CONFIG.staticFiles.indexOf(url.pathname) !== -1) return true;
  for (var i = 0; i < CONFIG.staticPrefixes.length; i++) {
    if (url.pathname.indexOf(CONFIG.staticPrefixes[i]) === 0) return true;
  }
  return false;
}

/** Only a plain, public, same-origin 200 is stored. */
function isCacheable(response) {
  if (!response || response.status !== 200 || response.type !== 'basic') return false;
  var cc = response.headers.get('Cache-Control') || '';
  if (/no-store|private/i.test(cc)) return false;
  if (response.headers.get('Vary') === '*') return false;
  return true;
}

function trim(cache) {
  return cache.keys().then(function (keys) {
    var extra = keys.length - CONFIG.maxStaticEntries;
    var jobs = [];
    for (var i = 0; i < extra; i++) jobs.push(cache.delete(keys[i]));
    return Promise.all(jobs);
  });
}

function cacheFirst(request) {
  return caches.open(STATIC_CACHE).then(function (cache) {
    return cache.match(request).then(function (hit) {
      if (hit) return hit;
      return fetch(request).then(function (response) {
        if (!isCacheable(response)) return response;
        var copy = response.clone();
        return cache.put(request, copy).then(function () { return trim(cache); }).then(function () { return response; });
      });
    });
  });
}

function offlineResponse() {
  return caches.open(OFFLINE_CACHE).then(function (cache) {
    return cache.match(CONFIG.offlineUrl);
  }).then(function (page) {
    return page || new Response('Offline', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
  });
}

self.addEventListener('install', function (event) {
  // 'reload' bypasses the HTTP cache so the offline page is current. If it cannot be fetched, the worker does not install.
  event.waitUntil(
    caches.open(OFFLINE_CACHE).then(function (cache) {
      return cache.add(new Request(CONFIG.offlineUrl, { cache: 'reload' }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (names) {
      return Promise.all(names.filter(function (name) {
        return name.indexOf(CONFIG.cachePrefix + '-') === 0 && name !== STATIC_CACHE && name !== OFFLINE_CACHE;
      }).map(function (name) { return caches.delete(name); }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') return;
  var url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.headers.get('Range')) return;

  // A page navigation always goes to the network (pages are per person); only a failed fetch shows the offline page.
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(function () { return offlineResponse(); }));
    return;
  }
  if (isNeverCached(url, request)) return;
  if (isStaticAsset(url)) event.respondWith(cacheFirst(request));
});
`;
}

/** Config with the shared defaults: static assets are the build output, the brand icons and the logo. */
export function defaultServiceWorkerConfig(overrides: Partial<ServiceWorkerConfig> & Pick<ServiceWorkerConfig, 'cachePrefix'>): ServiceWorkerConfig {
  return {
    version: PWA_CACHE_VERSION,
    offlineUrl: '/offline',
    neverCache: COMMON_NEVER_CACHE,
    staticPrefixes: ['/_next/static/', '/icons/'],
    staticFiles: ['/logo-mark.svg'],
    maxStaticEntries: 150,
    ...overrides
  };
}
