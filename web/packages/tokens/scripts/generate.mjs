// Generates src/generated/tokens.ts from src/tokens.css so native apps (React Native) and TS code get
// a typed token object from the single CSS source. Run: pnpm --filter @afrotransact/tokens generate
import { mkdirSync,readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cssPath = resolve(here, '../src/tokens.css');
const outPath = resolve(here, '../src/generated/tokens.ts');
const fontsConfigPath = resolve(here, '../src/fonts.config.json');
const fontsCssPath = resolve(here, '../src/fonts.css');
const fontsTsPath = resolve(here, '../src/generated/fonts.ts');

const quote = (n) => (/[\s]/.test(n) ? `"${n}"` : n);
/** A CSS font stack: the family (quoted) then its fallbacks (multi-word names quoted, generic keywords bare). */
export function fontStack(face) {
  const names = [face.family ? `"${face.family}"` : null, ...face.fallback.map(quote)].filter(Boolean);
  return names.join(', ');
}

/** The --at-font-* declarations of tokens.css, from fonts.config.json. */
export function fontDeclarations(cfg) {
  return [
    `  --at-font-sans: ${fontStack(cfg.sans)};`,
    `  --at-font-display: ${fontStack(cfg.display)};`,
    `  --at-font-mono: ${fontStack(cfg.mono)};`
  ].join('\n');
}

/** Rewrites the block between the fonts markers of tokens.css. */
export function withFonts(css, cfg) {
  return css.replace(/(\/\* fonts:start[^*]*\*\/\n)[\s\S]*?(\n\s*\/\* fonts:end \*\/)/, `$1${fontDeclarations(cfg)}$2`);
}

export function renderFontsCss(cfg) {
  const imports = ['sans', 'display'].flatMap((k) => cfg[k].weights.map((w) => `@import '${cfg[k].package}/latin-${w}.css';`));
  return [
    '/* GENERATED by scripts/generate.mjs from fonts.config.json — do not edit by hand. Self-hosted latin subsets, font-display: swap. */',
    ...imports,
    ''
  ].join('\n');
}

export function renderFontsTs(cfg) {
  const googleFamily = (face) => `family=${face.family.replace(/ /g, '+')}:wght@${face.weights.join(';')}`;
  const body = {
    sans: { family: cfg.sans.family, stack: fontStack(cfg.sans), weights: cfg.sans.weights },
    display: { family: cfg.display.family, stack: fontStack(cfg.display), weights: cfg.display.weights },
    /** For iframes that cannot use the page's self-hosted files (Stripe Elements / Connect.js). */
    googleFontsUrl: `https://fonts.googleapis.com/css2?${googleFamily(cfg.sans)}&${googleFamily(cfg.display)}&display=swap`
  };
  return [
    '// GENERATED by scripts/generate.mjs from src/fonts.config.json — do not edit by hand.',
    '/* eslint-disable */',
    `export const fonts = ${JSON.stringify(body, null, 2)} as const;`,
    ''
  ].join('\n');
}

export function parseCssVariables(css) {
  const root = /:root\s*\{([\s\S]*?)\n\}/.exec(css);
  if (!root) throw new Error('No :root block in tokens.css');
  const body = root[1].replace(/\/\*[\s\S]*?\*\//g, '');
  const vars = {};
  for (const m of body.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) vars[m[1]] = m[2].trim();
  return vars;
}

export function resolveVariables(vars) {
  const out = {};
  const resolveOne = (name, seen = new Set()) => {
    if (name in out) return out[name];
    if (seen.has(name)) throw new Error('Cycle at ' + name);
    seen.add(name);
    const raw = vars[name];
    if (raw === undefined) throw new Error('Unknown token ' + name);
    const value = raw.replace(/var\((--[a-z0-9-]+)\)/gi, (_, ref) => resolveOne(ref, seen));
    out[name] = value;
    return value;
  };
  Object.keys(vars).forEach((n) => resolveOne(n));
  return out;
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

export function toTree(resolved) {
  const tree = {};
  for (const [name, value] of Object.entries(resolved)) {
    const bare = name.replace(/^--(at-)?/, '');
    const [group, ...rest] = bare.split('-');
    const key = rest.length ? camel(rest.join('-')) : 'value';
    (tree[group] ??= {})[key] = value;
  }
  return tree;
}

export function render(css) {
  const vars = parseCssVariables(css);
  const resolved = resolveVariables(vars);
  const tree = toTree(resolved);
  return [
    '// GENERATED by scripts/generate.mjs from src/tokens.css — do not edit by hand.',
    '/* eslint-disable */',
    '',
    '/** CSS custom properties exactly as declared (values may reference other tokens). */',
    `export const cssVariables = ${JSON.stringify(vars, null, 2)} as const;`,
    '',
    '/** Every token with var() references resolved to concrete values (for React Native and canvas use). */',
    `export const resolvedVariables = ${JSON.stringify(resolved, null, 2)} as const;`,
    '',
    '/** Resolved tokens grouped by family, e.g. tokens.color.canvas, tokens.gold["500"], tokens.space["4"]. */',
    `export const tokens = ${JSON.stringify(tree, null, 2)} as const;`,
    ''
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const fontsCfg = JSON.parse(readFileSync(fontsConfigPath, 'utf8'));
  writeFileSync(cssPath, withFonts(readFileSync(cssPath, 'utf8'), fontsCfg));
  writeFileSync(fontsCssPath, renderFontsCss(fontsCfg));
  mkdirSync(dirname(fontsTsPath), { recursive: true });
  writeFileSync(fontsTsPath, renderFontsTs(fontsCfg));
  const out = render(readFileSync(cssPath, 'utf8'));
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, out);
  console.log('Wrote ' + outPath);
}
