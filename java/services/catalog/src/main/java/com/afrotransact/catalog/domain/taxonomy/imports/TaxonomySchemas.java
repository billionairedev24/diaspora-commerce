package com.afrotransact.catalog.domain.taxonomy.imports;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import com.afrotransact.catalog.domain.AttributeDefinition;
import com.afrotransact.catalog.domain.AttributeKind;
import com.afrotransact.catalog.domain.AttributeSection;
import com.afrotransact.catalog.domain.IdentifierRule;
import com.afrotransact.catalog.domain.ProductTypeTraits;
import com.afrotransact.catalog.domain.VariationDimension;
import com.afrotransact.catalog.domain.VariationTheme;
import com.afrotransact.catalog.domain.sizing.MeasurementUnit;
import com.afrotransact.catalog.domain.sizing.SizingTrait;
import com.afrotransact.catalog.domain.sizing.SuggestedMeasurement;

/**
 * The detail questions, variation themes, traits and sizing of the product types (resource
 * {@code taxonomy/schemas.json}, generated by {@code tools/seed/catalog_taxonomy.py}): what a seller fills in besides
 * the tax questions. Read from parsed JSON.
 */
public final class TaxonomySchemas {

    /** One schema: detail attributes, themes, identifier rule, traits and sizing. */
    public record Schema(IdentifierRule identifierRule, ProductTypeTraits traits, List<AttributeDefinition> attributes,
                         List<VariationTheme> themes) {
    }

    /** A category that is not in the tax document (provisional until the owner decides). */
    public record Provisional(String code, String department, String name, String status, String productType,
                              List<String> statusReasons) {
    }

    private final Map<String, Object> families;
    private final Map<String, Object> departments;
    private final Map<String, Object> categories;
    private final Map<String, Object> productTypes;
    private final List<Provisional> provisional;
    private final Map<String, Object> compliance;

    @SuppressWarnings("unchecked")
    public TaxonomySchemas(Map<String, Object> root) {
        this.families = (Map<String, Object>) root.get("families");
        this.departments = (Map<String, Object>) root.get("departments");
        this.categories = (Map<String, Object>) root.get("categories");
        this.productTypes = (Map<String, Object>) root.get("productTypes");
        this.compliance = (Map<String, Object>) root.getOrDefault("departmentCompliance", Map.of());
        List<Provisional> p = new ArrayList<>();
        for (Object o : (List<Object>) root.getOrDefault("provisional", List.of())) {
            Map<String, Object> m = (Map<String, Object>) o;
            p.add(new Provisional(String.valueOf(m.get("code")), String.valueOf(m.get("department")),
                    String.valueOf(m.get("name")), String.valueOf(m.get("status")), String.valueOf(m.get("productType")),
                    ((List<Object>) m.getOrDefault("statusReasons", List.of())).stream().map(String::valueOf).toList()));
        }
        this.provisional = List.copyOf(p);
    }

    public List<Provisional> provisional() {
        return provisional;
    }

    /** What sellers must have on file for a department (BEAUTY_LABELLING ...). */
    public Set<String> complianceOf(String departmentCode) {
        Object c = compliance.get(departmentCode);
        return c instanceof List<?> l ? Set.copyOf(l.stream().map(String::valueOf).toList()) : Set.of();
    }

    /**
     * The schema of a product type of a category: the type's own override (fashion sizing), else the category's
     * family, else its department's.
     */
    @SuppressWarnings("unchecked")
    public Schema schemaFor(String departmentCode, String categoryCode, String typeCode) {
        Map<String, Object> own = (Map<String, Object>) productTypes.get(typeCode);
        if (own != null) {
            return read(own);
        }
        Object family = categories.get(categoryCode);
        String name = family != null ? family.toString() : String.valueOf(departments.get(departmentCode));
        Map<String, Object> f = (Map<String, Object>) families.get(name);
        if (f == null) {
            throw new IllegalArgumentException("No schema family " + name + " for " + categoryCode);
        }
        return read(f);
    }

    @SuppressWarnings("unchecked")
    private static Schema read(Map<String, Object> m) {
        List<AttributeDefinition> attributes = new ArrayList<>();
        for (Object o : (List<Object>) m.getOrDefault("attributes", List.of())) {
            attributes.add(attribute((Map<String, Object>) o));
        }
        List<VariationTheme> themes = new ArrayList<>();
        for (Object o : (List<Object>) m.getOrDefault("themes", List.of())) {
            Map<String, Object> t = (Map<String, Object>) o;
            List<VariationDimension> dims = new ArrayList<>();
            for (Object d : (List<Object>) t.get("dimensions")) {
                Map<String, Object> dm = (Map<String, Object>) d;
                dims.add(new VariationDimension(String.valueOf(dm.get("name")),
                        ((List<Object>) dm.get("options")).stream().map(String::valueOf).toList(),
                        Boolean.TRUE.equals(dm.get("allowCustomValues"))));
            }
            themes.add(new VariationTheme(String.valueOf(t.get("name")), dims));
        }
        Map<String, Object> tr = (Map<String, Object>) m.getOrDefault("traits", Map.of());
        SizingTrait sizing = null;
        if (m.get("sizing") instanceof Map<?, ?> sm) {
            List<SuggestedMeasurement> measurements = new ArrayList<>();
            for (Object o : (List<Object>) sm.get("suggestedMeasurements")) {
                Map<String, Object> mm = (Map<String, Object>) o;
                measurements.add(new SuggestedMeasurement(String.valueOf(mm.get("key")), String.valueOf(mm.get("label")),
                        MeasurementUnit.valueOf(String.valueOf(mm.get("unit"))),
                        mm.get("help") == null ? null : String.valueOf(mm.get("help"))));
            }
            sizing = new SizingTrait(Boolean.TRUE.equals(sm.get("sizeChartRequired")),
                    String.valueOf(sm.get("sizeDimension")), measurements);
        }
        ProductTypeTraits traits = new ProductTypeTraits(Boolean.TRUE.equals(tr.get("food")),
                Boolean.TRUE.equals(tr.get("perishable")), Boolean.TRUE.equals(tr.get("regulated")),
                Boolean.TRUE.equals(tr.get("preorder")), sizing);
        return new Schema(IdentifierRule.valueOf(String.valueOf(m.getOrDefault("identifierRule", "GTIN"))), traits,
                attributes, themes);
    }

    @SuppressWarnings("unchecked")
    private static AttributeDefinition attribute(Map<String, Object> m) {
        Map<String, Object> copy = new LinkedHashMap<>(m);
        return new AttributeDefinition(String.valueOf(copy.get("key")), String.valueOf(copy.get("label")),
                ((List<Object>) copy.getOrDefault("options", List.of())).stream().map(String::valueOf).toList(),
                Boolean.TRUE.equals(copy.get("required")), Boolean.TRUE.equals(copy.get("multiline")),
                AttributeKind.valueOf(String.valueOf(copy.get("kind"))),
                ((List<Object>) copy.getOrDefault("units", List.of())).stream().map(String::valueOf).toList(),
                AttributeSection.valueOf(String.valueOf(copy.getOrDefault("section", "DETAILS"))),
                copy.get("help") == null ? null : String.valueOf(copy.get("help")), true);
    }
}
