-- Seller-written size charts and sizes for fashion (and any sized) product types.
-- A seller writes a chart once (measurement columns and one row per size label) and links it to any number of their
-- products (the link, size_chart_id and a fit note, lives in product.listing). Staff only mark a product type as sized
-- (the `sizing` trait of product_type.traits); the section at the end does that for the seeded fashion types.

create table size_chart (
    id                uuid primary key,
    owner_org         varchar(80)  not null,
    name              varchar(80)  not null,
    unit_system       varchar(2)   not null check (unit_system in ('CM', 'IN')),
    product_type_code varchar(40)  references product_type (code),
    category_id       uuid         references category (id),
    columns           jsonb        not null,
    rows              jsonb        not null,
    fit_note          varchar(20)  check (fit_note in ('RUNS_SMALL', 'TRUE_TO_SIZE', 'RUNS_LARGE')),
    how_to_measure    text,
    retired_at        timestamptz,
    created_by        varchar(120) not null,
    created_at        timestamptz  not null,
    updated_at        timestamptz  not null,
    version           bigint       not null default 0
);
-- A seller's active charts have different names whatever their case (the bulk upload matches charts by name).
create unique index size_chart_owner_name on size_chart (owner_org, lower(name)) where retired_at is null;
create index size_chart_owner on size_chart (owner_org, updated_at desc);

-- Which products use a chart (retire warns, chart edits check the sizes still sold).
create index product_size_chart on product ((listing ->> 'sizeChartId')) where listing ? 'sizeChartId';

-- Structural taxonomy: the fashion product types are sized and sellers may write their own sizes and colours.
-- Generated by `python3 tools/seed/catalog_taxonomy.py --sizing`; only flags and the trait are added, so values staff
-- edited since V2 are kept. sizeChartRequired stays off: staff switch it on per category once sellers have charts.
update product_type set themes = (select jsonb_agg(jsonb_set(t.theme, '{dimensions}', (
                       select jsonb_agg(case when d.dim ->> 'name' in ('Size', 'Color') then d.dim || '{"allowCustomValues": true}'::jsonb
                                             else d.dim end order by d.pos)
                       from jsonb_array_elements(t.theme -> 'dimensions') with ordinality as d(dim, pos))) order by t.pos)
                   from jsonb_array_elements(themes) with ordinality as t(theme, pos)),
       traits = traits || '{"sizing": {"sizeChartRequired": false, "sizeDimension": "Size", "suggestedMeasurements": [{"key": "bust", "label": "Bust", "unit": "CM", "help": "Around the fullest part of the bust"}, {"key": "waist", "label": "Waist", "unit": "CM", "help": "Around the narrowest part"}, {"key": "hip", "label": "Hip", "unit": "CM", "help": "Around the fullest part of the hips"}]}}'::jsonb,
       version = version + 1, updated_at = now() where code = 'dress';

