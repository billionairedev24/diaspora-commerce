#!/usr/bin/env python3
"""Generate one path-filtered caller workflow per service / web app, plus promote.yml.

Services = PORTS.md table UNION java/services/*/pom.xml and go/services/*/go.mod on disk; web apps =
the three planned apps UNION web/apps/*/package.json.

Every service in infra/local/PORTS.md gets .github/workflows/<runtime>-<service>.yml calling the reusable
_java-service.yml / _go-service.yml (+ _deploy.yml to dev on main). Workflows for services whose directory
does not exist yet are harmless: their path filters never match, and the reusable pipeline's `meta` job
skips everything if the directory is missing (e.g. on workflow_dispatch).

    python3 tools/ci/gen_workflows.py          # (re)write the files
    python3 tools/ci/gen_workflows.py --check  # CI: fail if the committed files are stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORKFLOWS = ROOT / ".github" / "workflows"
PORTS = ROOT / "infra" / "local" / "PORTS.md"
HEADER = "# GENERATED by tools/ci/gen_workflows.py - edit the generator, not this file.\n"

WEB_APPS = ["storefront", "seller-center", "staff-console"]


def services_from_ports() -> list[tuple[str, str]]:
    """(name, runtime) from the service table in PORTS.md; runtime is 'java' or 'go'."""
    rows: list[tuple[str, str]] = []
    for line in PORTS.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*([a-z][a-z0-9-]*)\s*\|\s*([^|]+?)\s*\|\s*(\d{4})\s*\|", line)
        if not m:
            continue
        name, runtime_text = m.group(1), m.group(2)
        if runtime_text.startswith("Spring Boot"):
            rows.append((name, "java"))
        elif runtime_text == "Go":
            rows.append((name, "go"))
    # Glob-driven: anything that exists on disk is covered even before PORTS.md lists it.
    known = {name for name, _ in rows}
    for pom in sorted(ROOT.glob("java/services/*/pom.xml")):
        if pom.parent.name not in known:
            rows.append((pom.parent.name, "java"))
    for mod in sorted(ROOT.glob("go/services/*/go.mod")):
        if mod.parent.name not in known:
            rows.append((mod.parent.name, "go"))
    if not rows:
        sys.exit(f"no services parsed from {PORTS}")
    return rows


def web_apps() -> list[str]:
    on_disk = [p.parent.name for p in sorted(ROOT.glob("web/apps/*/package.json"))]
    return sorted(set(WEB_APPS) | set(on_disk))


def service_workflow(name: str, runtime: str) -> str:
    if runtime == "java":
        paths = [
            f"java/services/{name}/**",
            "java/libs/**",
            "java/platform-parent/**",
            "java/config/**",
            "java/Dockerfile",
            "java/.mvn/**",
            "java/mvnw",
        ]
    else:
        paths = [
            f"go/services/{name}/**",
            "go/pkg/**",
            "go/.golangci.yml",
        ]
    paths += [
        f"contracts/openapi/{name}.yaml",
        "infra/helm/library/**",
        f".github/workflows/{runtime}-{name}.yml",
        f".github/workflows/_{runtime}-service.yml",
        ".github/actions/publish-image/**",
        ".github/actions/helm-check/**",
    ]
    path_yaml = "\n".join(f"      - {p}" for p in paths)
    return f"""{HEADER}# {name} ({runtime}): build, test, scan, sign on every change to this service only; deploy to dev on main.
name: {runtime}-{name}

on:
  push:
    branches: [main]
    paths:
{path_yaml}
  pull_request:
    paths:
{path_yaml}
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: {runtime}-{name}-${{{{ github.ref }}}}
  cancel-in-progress: ${{{{ github.event_name == 'pull_request' }}}}

jobs:
  pipeline:
    uses: ./.github/workflows/_{runtime}-service.yml
    permissions:
      contents: read
      packages: write
      id-token: write
      security-events: write
    with:
      service: {name}
      publish: ${{{{ github.event_name != 'pull_request' && github.ref == 'refs/heads/main' }}}}

  deploy-dev:
    needs: pipeline
    if: github.event_name != 'pull_request' && github.ref == 'refs/heads/main' && needs.pipeline.outputs.exists == 'true'
    uses: ./.github/workflows/_deploy.yml
    permissions:
      contents: write
      packages: read
      id-token: write
    with:
      service: {name}
      environment: dev
      tag: ${{{{ needs.pipeline.outputs.tag }}}}
    secrets: inherit
"""


def web_workflow(app: str) -> str:
    paths = [
        f"web/apps/{app}/**",
        "web/packages/**",
        "web/package.json",
        "web/pnpm-lock.yaml",
        "web/pnpm-workspace.yaml",
        f".github/workflows/web-{app}.yml",
        ".github/workflows/_web-app.yml",
    ]
    path_yaml = "\n".join(f"      - {p}" for p in paths)
    return f"""{HEADER}# {app} (web): PR -> Cloudflare preview URL; main -> dev; manual dispatch -> uat/prod (prod needs approval).
name: web-{app}

on:
  push:
    branches: [main]
    paths:
{path_yaml}
  pull_request:
    paths:
{path_yaml}
  workflow_dispatch:
    inputs:
      environment:
        description: Target environment
        type: choice
        options: [dev, uat, prod]
        default: uat
      vercel:
        description: Also deploy to Vercel (fallback)
        type: boolean
        default: false

permissions:
  contents: read

concurrency:
  group: web-{app}-${{{{ github.ref }}}}-${{{{ inputs.environment || 'auto' }}}}
  cancel-in-progress: ${{{{ github.event_name == 'pull_request' }}}}

jobs:
  web:
    uses: ./.github/workflows/_web-app.yml
    permissions:
      contents: read
      pull-requests: write
    with:
      app: {app}
      target: ${{{{ github.event_name == 'pull_request' && 'preview' || (github.event_name == 'workflow_dispatch' && inputs.environment || 'dev') }}}}
      vercel: ${{{{ github.event_name == 'workflow_dispatch' && inputs.vercel || vars.VERCEL_FALLBACK == 'true' }}}}
    secrets: inherit
"""


def promote_workflow(services: list[tuple[str, str]]) -> str:
    options = ", ".join(name for name, _ in services)
    return f"""{HEADER}# Promote an already-built, signed image of ONE service to uat or prod (prod waits for the
# `production` reviewers configured on the GitHub environment `prod`). Default tag = what dev runs now.
name: promote

on:
  workflow_dispatch:
    inputs:
      service:
        description: Service
        type: choice
        options: [{options}]
      environment:
        description: Target environment
        type: choice
        options: [uat, prod]
        default: uat
      tag:
        description: Image tag (full git sha). Empty = the tag in values-dev.yaml (uat) / values-uat.yaml (prod).
        type: string
        default: ""

permissions:
  contents: read

jobs:
  resolve:
    runs-on: ubuntu-latest
    outputs:
      tag: ${{{{ steps.tag.outputs.tag }}}}
    steps:
      - uses: actions/checkout@v7
      - id: tag
        env:
          SERVICE: ${{{{ inputs.service }}}}
          TARGET: ${{{{ inputs.environment }}}}
          TAG: ${{{{ inputs.tag }}}}
        run: |
          if [[ -z "$TAG" ]]; then
            from=$([[ "$TARGET" == prod ]] && echo uat || echo dev)
            dir=$([[ -d "java/services/$SERVICE" ]] && echo "java/services/$SERVICE" || echo "go/services/$SERVICE")
            TAG="$(yq '.image.tag // ""' "$dir/deploy/helm/values-$from.yaml")"
          fi
          [[ "$TAG" =~ ^[0-9a-f]{{40}}$ ]] || {{ echo "::error::no deployable tag for $SERVICE ($TAG)"; exit 1; }}
          echo "tag=$TAG" >> "$GITHUB_OUTPUT"

  deploy:
    needs: resolve
    uses: ./.github/workflows/_deploy.yml
    permissions:
      contents: write
      packages: read
      id-token: write
    with:
      service: ${{{{ inputs.service }}}}
      environment: ${{{{ inputs.environment }}}}
      tag: ${{{{ needs.resolve.outputs.tag }}}}
    secrets: inherit
"""


def render() -> dict[Path, str]:
    services = services_from_ports()
    files: dict[Path, str] = {}
    for name, runtime in services:
        files[WORKFLOWS / f"{runtime}-{name}.yml"] = service_workflow(name, runtime)
    for app in web_apps():
        files[WORKFLOWS / f"web-{app}.yml"] = web_workflow(app)
    files[WORKFLOWS / "promote.yml"] = promote_workflow(services)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    files = render()
    stale = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    # Generated files that no longer correspond to a service.
    expected = set(files)
    for path in WORKFLOWS.glob("*.yml"):
        if path not in expected and path.read_text(encoding="utf-8").startswith(HEADER):
            if args.check:
                stale.append(path.relative_to(ROOT))
            else:
                path.unlink()
                print(f"removed {path.relative_to(ROOT)}")

    if stale:
        print("stale generated workflows (run python3 tools/ci/gen_workflows.py):", *stale, sep="\n  ")
        return 1
    print(f"{len(files)} generated workflows up to date" if args.check else "done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
