#!/usr/bin/env python3
"""Every public hostname comes from ONE map (infra/cloudflare/hosts.json); this tool prints it, proves the repository agrees with it
and moves the trial to another zone.

Cloudflare's FREE Universal certificate covers the zone apex and ONE label below it, so no host is more than one label under the zone:

    prod         afrotransact.com (storefront)   seller.  admin.  api.  auth.  media.  developers.          <role>.afrotransact.com
    uat          uat.afrotransact.com            seller-uat.   admin-uat.   api-uat.   auth-uat.   media-uat.   developers-uat.
    dev          dev.afrotransact.com            seller-dev.   admin-dev.   api-dev.   auth-dev.   media-dev.   developers-dev.
    trial        test.afrotransact.com           seller-test.  admin-test.  api-test.  auth-test.  media-test.  developers-test.

    python3 tools/ci/env_hosts.py show [env]          the host table (markdown)
    python3 tools/ci/env_hosts.py check               exit 1 when any file names a host that is not in the map (used by `make env-check`)
    python3 tools/ci/env_hosts.py sync                rewrite the generated host blocks of infra/argocd/envs/*/platform-values.yaml
    python3 tools/ci/env_hosts.py env <env> [zone]    KEY=value lines (zone, *_host, *_url, bff_origin) for workflows; validates the zone
    python3 tools/ci/env_hosts.py set-trial-zone <zone>   the trial may live in its own zone: rewrite the trial's files (and its "zone" in the map)

What `check` proves: the map itself (one label under the zone), global.domain/webHost/sellerHost/adminHost/apiHost/authHost/mediaHost of
every Argo CD environment, the HTTPRoute hostnames of every edge overlay, the hosts in every web wrangler.jsonc environment and every
mobile eas.json build profile. tools/ci/check_env_urls.py (also in `make env-check`) proves no other file names a host and that no host
anywhere is more than one label below the zone. Standard library only.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAP = ROOT / "infra/cloudflare/hosts.json"
DNS = re.compile(r"^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$")
PV = "infra/argocd/envs/{env}/platform-values.yaml"
BEGIN, END = "  # HOSTS BEGIN (generated by tools/ci/env_hosts.py sync; edit infra/cloudflare/hosts.json)", "  # HOSTS END"
WRANGLER_ENV = {"dev": None, "uat": "uat", "prod": "prod", "trial": "trial"}  # env -> key under "env" (dev = top level, preview also dev)
EAS_ENV = {"development": "dev", "preview": "uat", "production": "prod"}


def load() -> dict:
    return json.loads(MAP.read_text())


def zone_of(m: dict, env: str) -> str:
    return m["envs"][env].get("zone", m["zone"])


def host(m: dict, env: str, role: str) -> str:
    """role: storefront | seller | admin | api | auth | media | developers | grafana | mcp"""
    suffix, zone = m["envs"][env]["suffix"], zone_of(m, env)
    if role == "storefront":
        return f"{suffix}.{zone}" if suffix else zone
    return f"{role}-{suffix}.{zone}" if suffix else f"{role}.{zone}"


def hosts(m: dict, env: str) -> dict[str, str]:
    return {r: host(m, env, r) for r in ["storefront", *m["roles"]]}


def all_hosts(m: dict, env: str) -> set[str]:
    return {host(m, env, r) for r in ["storefront", *m["roles"], *m["other_roles"]]}


def labels_below(h: str, zone: str) -> int:
    return 0 if h == zone else h[: -len(zone) - 1].count(".") + 1


def table(m: dict, only: str | None = None) -> str:
    cols = ["storefront", *m["roles"]]
    out = ["| env | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for env in m["envs"]:
        if only and env != only:
            continue
        out.append(f"| {env} | " + " | ".join(host(m, env, c) for c in cols) + " |")
    return "\n".join(out)


def pv_block(m: dict, env: str) -> str:
    h = hosts(m, env)
    keys = [("domain", zone_of(m, env)), ("webHost", h["storefront"]), ("sellerHost", h["seller"]), ("adminHost", h["admin"]),
            ("apiHost", h["api"]), ("authHost", h["auth"]), ("mediaHost", h["media"])]
    return BEGIN + "\n" + "\n".join(f"  {k}: {v}" for k, v in keys) + "\n" + END


def read_pv_block(env: str) -> dict[str, str]:
    text = (ROOT / PV.format(env=env)).read_text()
    a, b = text.index(BEGIN), text.index(END)
    return dict(re.findall(r"^\s+(\w+):\s*(\S+)\s*$", text[a + len(BEGIN):b], re.M))


def sync() -> int:
    m = load()
    for env in m["envs"]:
        p = ROOT / PV.format(env=env)
        text = p.read_text()
        block = pv_block(m, env)
        if BEGIN in text:
            a, b = text.index(BEGIN), text.index(END) + len(END)
            text = text[:a] + block + text[b:]
        else:  # first time: replace the old domain / storefrontHost lines of the global: section
            text = re.sub(r"^global:\n(?:  .*\n|\s*\n)*?(?=\S)", "global:\n" + block + "\n\n", text, count=1, flags=re.M)
        p.write_text(text)
        print(f"updated {p.relative_to(ROOT)}")
    return check()


def jsonc(path: Path) -> dict:
    return json.loads("\n".join(l for l in path.read_text().splitlines() if not l.strip().startswith("//")))


def hosts_in(value) -> set[str]:
    return set(re.findall(r"https?://([A-Za-z0-9.-]+)", json.dumps(value)))


def check() -> int:
    m = load()
    bad = 0

    def fail(msg: str) -> None:
        nonlocal bad
        bad += 1
        print(msg)

    for env in m["envs"]:
        zone = zone_of(m, env)
        if not DNS.match(zone):
            fail(f"hosts.json: zone {zone!r} of {env} is not a DNS name")
        for r in [*m["roles"], "storefront", *m["other_roles"]]:
            h = host(m, env, r)
            if labels_below(h, zone) > 1:
                fail(f"hosts.json: {env} {r} {h} is more than one label below {zone} (the free certificate would not cover it)")
        want = hosts(m, env)
        # Argo CD values
        got = read_pv_block(env)
        exp = {"domain": zone, "webHost": want["storefront"], "sellerHost": want["seller"], "adminHost": want["admin"],
               "apiHost": want["api"], "authHost": want["auth"], "mediaHost": want["media"]}
        for k, v in exp.items():
            if got.get(k) != v:
                fail(f"{PV.format(env=env)}: global.{k} is {got.get(k)!r}, the map says {v!r} (run tools/ci/env_hosts.py sync)")
        # edge overlays: hostnames of the HTTPRoutes
        edge = ROOT / f"infra/k8s/platform/edge/overlays/{env}"
        text_all = " ".join(f.read_text() for f in edge.glob("*.yaml"))
        names = set(re.findall(r"[a-z0-9][a-z0-9.-]*\." + re.escape(zone), text_all)) | ({zone} if re.search(r"\[" + re.escape(zone) + r"\]", text_all) else set())
        extra = names - all_hosts(m, env)
        if extra:
            fail(f"{edge.relative_to(ROOT)}: hostnames {sorted(extra)} are not in the map for {env}")
        for must in (want["api"], want["auth"]):
            if must not in names:
                fail(f"{edge.relative_to(ROOT)}: route host {must} missing")
    # wrangler: dev = top level and env.preview, uat/prod/trial = env.<name>
    for app in ("storefront", "seller-center", "staff-console"):
        path = ROOT / f"web/apps/{app}/wrangler.jsonc"
        cfg = jsonc(path)
        blocks = {"dev": cfg, "preview": cfg["env"]["preview"], **{e: cfg["env"][e] for e in ("uat", "prod", "trial") if e in cfg["env"]}}
        if "trial" not in cfg["env"]:
            fail(f"{path.relative_to(ROOT)}: no trial environment")
        for name, blk in blocks.items():
            env = "dev" if name == "preview" else name
            extra = hosts_in([blk.get("vars", {}), blk.get("routes", [])]) - all_hosts(m, env)
            if extra:
                fail(f"{path.relative_to(ROOT)}: {name} names {sorted(extra)}, not in the map for {env}")
    # mobile builds
    for app in ("customer", "driver"):
        path = ROOT / f"mobile/apps/{app}/eas.json"
        if not path.exists():
            continue
        for prof, blk in jsonc(path).get("build", {}).items():
            env = EAS_ENV.get(prof)
            if env:
                extra = hosts_in(blk) - all_hosts(m, env)
                if extra:
                    fail(f"{path.relative_to(ROOT)}: profile {prof} names {sorted(extra)}, not in the map for {env}")
    print("env_hosts: " + ("FAILED" if bad else "OK - one source, every env one label below the zone\n" + table(m)))
    return 1 if bad else 0


def env_lines(env: str, zone: str | None = None) -> int:
    m = load()
    if env not in m["envs"]:
        print(f"error: env {env!r} not in {MAP.relative_to(ROOT)}", file=sys.stderr)
        return 2
    if zone:
        zone = zone.strip().lower()
        if not DNS.match(zone) or zone.count(".") < 1:
            print(f"error: zone {zone!r} must be a bare lower-case DNS name such as example.com", file=sys.stderr)
            return 2
        m["envs"][env]["zone"] = zone
    h = hosts(m, env)
    print(f"zone={zone_of(m, env)}")
    for k, v in h.items():
        print(f"{k}_host={v}")
        print(f"{k}_url=https://{v}")
    print(f"bff_origin=https://{h['api']}/bff")
    return 0


def set_trial_zone(new: str) -> int:
    new = new.strip().lower()
    if not DNS.match(new) or new.count(".") < 1:
        print(f"error: {new!r} is not a bare lower-case DNS name such as example.com", file=sys.stderr)
        return 2
    m = load()
    old = zone_of(m, "trial")
    if old == new:
        print(f"the trial zone is already {new}")
        return check()
    text = MAP.read_text()
    m["envs"]["trial"]["zone"] = new
    suffix = m["envs"]["trial"]["suffix"]
    text = re.sub(r'"trial": \{[^}]*\}', f'"trial": {{ "suffix": "{suffix}", "zone": "{new}" }}', text)
    MAP.write_text(text)
    files = [ROOT / "infra/cloudflare/envs/trial.tfvars", ROOT / PV.format(env="trial"),
             *(ROOT / "infra/k8s/platform/edge/overlays/trial").glob("*.yaml")]
    for f in files:
        f.write_text(f.read_text().replace(old, new))
    for app in ("storefront", "seller-center", "staff-console"):
        p = ROOT / f"web/apps/{app}/wrangler.jsonc"
        t = p.read_text()
        i = t.index('"trial"')
        p.write_text(t[:i] + t[i:].replace(old, new))
    print(f"trial moved from {old} to {new}")
    return check()


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    if cmd == "show" and len(argv) in (1, 2):
        print(table(load(), argv[1] if len(argv) == 2 else None))
        return 0
    if cmd == "check" and len(argv) == 1:
        return check()
    if cmd == "sync" and len(argv) == 1:
        return sync()
    if cmd == "env" and len(argv) in (2, 3):
        return env_lines(*argv[1:])
    if cmd == "set-trial-zone" and len(argv) == 2:
        return set_trial_zone(argv[1])
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
