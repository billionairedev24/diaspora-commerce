#!/usr/bin/env python3
"""Generate the tax-returns seed migration from tools/taxonomy/category_tax_map.json.

    python3 tools/taxonomy/gen_seed_sql.py           write V12__seed_category_tax_profiles.sql
    python3 tools/taxonomy/gen_seed_sql.py --check   fail (exit 1) when the committed file is stale

Deterministic: same JSON in, same bytes out (insertion order is the file order; JSON columns use sorted-free compact
dumps). The generated SQL is data only; the tables are created by V10 and V11. Flyway migrations are immutable once
applied, so a rule change is a NEW migration (V13 and up) made from the changed dataset, never an edit of V12: run the
script with --out and rename. `make taxonomy-check` runs --check through tools/taxonomy/tests/test_gen_seed_sql.py.
NOT TAX OR LEGAL ADVICE: draft rules; a Texas tax professional must approve before production use.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
MAP = HERE / "category_tax_map.json"
OUT = REPO / "java/services/tax-returns/src/main/resources/db/migration/V12__seed_category_tax_profiles.sql"


def q(value):
    """SQL literal for a string or None."""
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"


def j(value):
    """jsonb literal (compact, key order as in the dataset)."""
    return q(json.dumps(value, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"


def b(value):
    return "true" if value else "false"


def generate(tax_map):
    out = []
    w = out.append
    w("-- GENERATED by tools/taxonomy/gen_seed_sql.py from tools/taxonomy/category_tax_map.json (do not edit by hand).")
    w("-- Rule version %s. DRAFT. NOT tax or legal advice: a Texas tax professional must approve before production use." % tax_map["ruleVersion"])
    w("-- Seeds fact definitions, 73 category profiles, their facts, 105 outcome codes and decision rows, and the provider code map")
    w("-- (STRIPE codes from the dataset, unverified; AVALARA empty and inactive until staff map them).")
    w("")
    w("insert into tax_rule_version (rule_version, base_version, reason, changed_by) values")
    w("    (%s, %s, %s, 'system:seed');" % (q(tax_map["ruleVersion"]), q(tax_map["ruleVersion"]), q("Seeded from the category tax map")))
    w("")
    w("insert into tax_fact_definition (id, label, kind, unit, owner, help, evidence, choices) values")
    rows = []
    for f in tax_map["facts"]:
        rows.append("    (%s, %s, %s, %s, %s, %s, %s, %s)" % (q(f["id"]), q(f["label"]), q(f["kind"]), q(f["unit"]), q(f["owner"]),
                                                              q(f["help"]), b(f["evidence"]), j(f.get("choices") or [])))
    w(",\n".join(rows) + ";")
    w("")
    depts = {d["code"]: d["name"] for d in tax_map["departments"]}
    w("insert into tax_profile (category_code, name, department_code, department_name, department_position, position, status,")
    w("                         status_reasons, default_outcome, stripe_codes, conflicting_codes, fact_groups, note) values")
    dpos = {d["code"]: d["position"] for d in tax_map["departments"]}
    rows = []
    for c in tax_map["categories"]:
        rows.append("    (%s, %s, %s, %s, %d, %d, %s, %s, %s, %s, %s, %s, %s)" % (
            q(c["code"]), q(c["name"]), q(c["department"]), q(depts[c["department"]]), dpos[c["department"]], c["position"], q(c["status"]),
            j(c["statusReasons"]), q(c["defaultOutcome"]), j(c["stripeCodes"]), j(c["conflictingCodes"]), j(c["factGroups"]),
            q(c["note"])))
    w(",\n".join(rows) + ";")
    w("")
    w("insert into tax_profile_fact (category_code, fact_id, position, required, required_when, choices) values")
    rows = []
    for c in tax_map["categories"]:
        for i, r in enumerate(c["facts"]):
            rows.append("    (%s, %s, %d, %s, %s, %s)" % (q(c["code"]), q(r["fact"]), i, b(r["required"]),
                                                          "null" if r["requiredWhen"] is None else j(r["requiredWhen"]),
                                                          j(r.get("choices") or [])))
    w(",\n".join(rows) + ";")
    w("")
    w("insert into tax_outcome_code (internal_tax_code, category_code, outcome, description, rate_display, note) values")
    rows = []
    for c in tax_map["categories"]:
        for r in c["decisionTable"]:
            rows.append("    (%s, %s, %s, %s, %s, %s)" % (q(r["internalTaxCode"]), q(c["code"]), q(r["outcome"]), q(r["condition"]),
                                                          q(r["rateDisplay"]), q(r["note"])))
    w(",\n".join(rows) + ";")
    w("")
    w("insert into tax_decision_row (id, category_code, position, scenario, when_expr, internal_tax_code) values")
    rows = []
    for c in tax_map["categories"]:
        for i, r in enumerate(c["decisionTable"]):
            rows.append("    (%s, %s, %d, %d, %s, %s)" % (q(r["id"]), q(c["code"]), i, r["scenario"],
                                                          "null" if r["when"] is None else j(r["when"]), q(r["internalTaxCode"])))
    w(",\n".join(rows) + ";")
    w("")
    w("insert into provider_code_map (internal_tax_code, provider, provider_code, active, verified, verified_note) values")
    rows = []
    for c in tax_map["categories"]:
        for r in c["decisionTable"]:
            for p in tax_map["providers"]:
                code = (r["providerCodes"] or {}).get(p)
                rows.append("    (%s, %s, %s, %s, false, %s)" % (q(r["internalTaxCode"]), q(p), q(code), b(code is not None),
                                                                 q("Seeded from the source document; not yet verified against the provider's treatment" if code else None)))
    w(",\n".join(rows) + ";")
    w("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when the committed migration is stale")
    ap.add_argument("--out", type=Path, default=OUT, help="output path (default: the V12 migration)")
    args = ap.parse_args()
    sql = generate(json.loads(MAP.read_text(encoding="utf-8")))
    if args.check:
        if not args.out.exists() or args.out.read_text(encoding="utf-8") != sql:
            print("%s is stale: run python3 tools/taxonomy/gen_seed_sql.py (a changed dataset needs a NEW migration, see --help)" % args.out, file=sys.stderr)
            return 1
        print("%s is current" % args.out.name)
        return 0
    args.out.write_text(sql, encoding="utf-8")
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
