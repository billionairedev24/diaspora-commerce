#!/usr/bin/env python3
"""Generates web/packages/api-client/src/mocks/staff/access-catalogue.ts (the mock BFF's permission catalogue and the roles
of the seller, provider and account portals) from identity's Flyway migrations, the way rbac-data.ts is generated for the
platform roles. Run from the repository root: python3 tools/identity/gen_access_fixture.py"""
import glob, json, re, sys

MIG = 'java/services/identity/src/main/resources/db/migration/*.sql'
files = sorted(glob.glob(MIG), key=lambda f: int(re.search(r'V(\d+)__', f).group(1)))
tup = re.compile(r"\(\s*'((?:[^']|'')*)'\s*,\s*'((?:[^']|'')*)'\s*(?:,\s*'((?:[^']|'')*)'\s*)?(?:,\s*(\d+)\s*)?\)")

perms, roles, rp = {}, {}, set()
for f in files:
    sql = open(f).read()
    sql = re.sub(r'--[^\n]*', '', sql)
    for m in re.finditer(r'insert\s+into\s+permission\s*\(([^)]*)\)\s*values(.*?)(?:on\s+conflict|;[ \t]*\n)', sql, re.S | re.I):
        for t in tup.finditer(m.group(2)):
            perms[t.group(1)] = (t.group(2), (t.group(3) or '').replace("''", "'"))
    for m in re.finditer(r'insert\s+into\s+role\s*\(key,\s*portal,\s*name,\s*description[^)]*\)\s*values(.*?)(?:on\s+conflict|;[ \t]*\n)', sql, re.S | re.I):
        for t in re.finditer(r"\(\s*'([^']+)'\s*,\s*'([^']+)'\s*,\s*'((?:[^']|'')*)'\s*,\s*'((?:[^']|'')*)'", m.group(1)):
            roles[t.group(1)] = (t.group(2).lower(), t.group(3).replace("''", "'"), t.group(4).replace("''", "'"))
    for m in re.finditer(r'insert\s+into\s+role_permission\s*\([^)]*\)\s*(values.*?)(?:on\s+conflict|;[ \t]*\n)', sql, re.S | re.I):
        for t in re.finditer(r"\(\s*'([^']+)'\s*,\s*'([^']+)'\s*\)", m.group(1)):
            rp.add((t.group(1), t.group(2)))

if len(perms) < 100 or not roles:
    sys.exit('parsed too little: %d permissions, %d roles' % (len(perms), len(roles)))

def q(s): return json.dumps(s, ensure_ascii=False)
out = ['/* Permission catalogue and the seller, provider and account roles of the mock staff BFF: GENERATED by tools/identity/gen_access_fixture.py',
       '   from identity\'s Flyway migrations (the platform roles are in rbac-data.ts). Do not edit by hand. */', '',
       'export const MOCK_PERMISSIONS: { key: string; module: string; description: string }[] = [']
for k in sorted(perms): out.append('  { key: %s, module: %s, description: %s },' % (q(k), q(perms[k][0]), q(perms[k][1])))
out += ['];', '', 'export const MOCK_OTHER_ROLES: { key: string; portal: string; name: string; description: string; permissions: string[] }[] = [']
for k, (portal, name, desc) in roles.items():
    if portal == 'platform': continue
    out.append('  { key: %s, portal: %s, name: %s, description: %s, permissions: %s },' % (q(k), q(portal), q(name), q(desc), json.dumps(sorted(p for r, p in rp if r == k))))
out += ['];', '']
open('web/packages/api-client/src/mocks/staff/access-catalogue.ts', 'w').write('\n'.join(out))
print(len(perms), 'permissions;', sum(1 for r in roles.values() if r[0] != 'platform'), 'other roles;', sum(1 for r in roles.values() if r[0] == 'platform'), 'platform roles')
