"""Merge contracts/asyncapi/fragments/*.yaml into contracts/asyncapi/events.yaml (AsyncAPI 3.0).

Each fragment contributes channels, operations and components; duplicate keys with different content fail
the merge so two services can't silently redefine the same event. Run in CI (contracts.yml) with --check.
"""
import glob
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "contracts", "asyncapi", "events.yaml")

BASE = {
    "asyncapi": "3.1.0",
    "info": {
        "title": "AfroTransact platform events",
        "version": "1.0.0",
        "description": "Every domain event on the bus. Topics are at.<aggregate>.events, keyed by aggregate id; "
                       "headers carry event-id, event-type and occurred-at. Producers use a transactional outbox; "
                       "consumers de-duplicate on event-id.",
    },
    "defaultContentType": "application/json",
    "servers": {
        "local": {"host": "localhost:9092", "protocol": "kafka"},
        "cloud": {"host": "pkc-xxxxx.confluent.cloud:9092", "protocol": "kafka-secure",
                  "description": "Confluent Cloud (same on AWS, GCP and Azure)"},
    },
    "channels": {},
    "operations": {},
    "components": {
        "schemas": {
            "EventHeaders": {
                "type": "object",
                "required": ["event-id", "event-type", "occurred-at"],
                "properties": {
                    "event-id": {"type": "string", "format": "uuid"},
                    "event-type": {"type": "string"},
                    "occurred-at": {"type": "string", "format": "date-time"},
                },
            }
        },
        "messages": {},
    },
}


def merge_into(target, source, where):
    for key, value in source.items():
        if key in target and target[key] != value:
            raise SystemExit("conflicting definition of %s.%s" % (where, key))
        target[key] = value


def build():
    doc = yaml.safe_load(yaml.safe_dump(BASE))
    for path in sorted(glob.glob(os.path.join(ROOT, "contracts", "asyncapi", "fragments", "*.yaml"))):
        with open(path, encoding="utf-8") as f:
            frag = yaml.safe_load(f) or {}
        name = os.path.basename(path)
        merge_into(doc["channels"], frag.get("channels", {}), name + ":channels")
        merge_into(doc["operations"], frag.get("operations", {}), name + ":operations")
        for section, values in (frag.get("components") or {}).items():
            doc["components"].setdefault(section, {})
            merge_into(doc["components"][section], values, name + ":components." + section)
    header = "# GENERATED by tools/contracts/merge_asyncapi.py from contracts/asyncapi/fragments — do not edit.\n"
    return header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)


def main():
    text = build()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            raise SystemExit("contracts/asyncapi/events.yaml is out of date; run tools/contracts/merge_asyncapi.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
