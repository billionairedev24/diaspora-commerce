#!/usr/bin/env python3
"""Generates docs/runbooks/release-1-config-inventory.md: every environment variable / secret NAME the two deployables read, where it is
set and who provides it. Sources (never values): infra/ovh-vps/secrets.sh (the Secret keys), the deployable charts' values files (Helm),
the modules' application-prod.yml and the Go config (what is read, `${VAR}` without a default = required), infra/argocd/envs/*/platform-values.yaml.
Run: python3 tools/release/config_inventory.py [--check]"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "docs/runbooks/release-1-config-inventory.md"
JAVA = "afrotransact-core"; GO = "afrotransact-go"
GO_SVC = {"gateway-bff", "cart", "search", "indexer", "geo", "media", "notifications"}

def secret_keys():
    """name -> {services, kind} from the service_keys function of secrets.sh."""
    text = (ROOT / "infra/ovh-vps/secrets.sh").read_text()
    sk = text[text.index("service_keys() {"):text.index("signing_key() {")]
    keys = {}; svc = None
    for line in sk.splitlines():
        m = re.match(r"\s{4}([a-z-]+)\)\s*(.*)", line)
        if m: svc = m.group(1)
        elif re.match(r"\s+(identity)\)", line): svc = "identity"
        for km in re.finditer(r'"([A-Z][A-Z0-9_]+)=([^"]*)"', line):
            k, v = km.groups()
            if k in ("APP_ENV",) or svc is None: continue
            kind = "generated" if ("$(gen" in v or "signing_key" in v or "$KAFKA" in v or "$REDIS" in v or "$MEILI" in v or "$FGA" in v or "$TEMPORAL" in v) else ("fixed" if "${" not in v and v != "" else ("third-party" if "${" in v else "empty"))
            keys.setdefault(k, {"svcs": set(), "kind": kind, "raw": v})["svcs"].add(svc)
    return keys

def helm_env(path):
    env = {}
    for f in ("values.yaml", "values-prod.yaml", "values-uat.yaml"):
        p = ROOT / path / f
        if not p.exists(): continue
        in_env = False
        for line in p.read_text().splitlines():
            if re.match(r"^extraEnv:", line): in_env = True; continue
            if in_env and re.match(r"^\S", line): in_env = False
            m = re.match(r"^\s{2}([A-Z][A-Z0-9_]+):\s*(.*?)\s*(#.*)?$", line)
            if in_env and m: env.setdefault(m.group(1), {})[f] = m.group(2).strip('"')
    return env

def app_reads():
    reads = {}
    for p in sorted((ROOT / "java/services").glob("*/src/main/resources/application*.yml")):
        mod = p.parts[-5]
        prof = p.name
        if prof not in ("application.yml", "application-prod.yml", "application-uat.yml"): continue
        for m in re.finditer(r"\$\{([A-Z][A-Z0-9_]+)(?::([^}]*))?\}", p.read_text()):
            k, d = m.group(1), m.group(2)
            e = reads.setdefault(k, {"mods": set(), "required": False, "default": None})
            e["mods"].add(mod)
            if d is None and prof != "application.yml": e["required"] = True
            if d is not None and e["default"] is None: e["default"] = d
    return reads

def main():
    sec = secret_keys(); core = helm_env("java/apps/core/deploy/helm"); go = helm_env("go/apps/afrotransact-go/deploy/helm")
    reads = app_reads()
    rows = []
    for k, v in sorted(sec.items()):
        d = GO if v["svcs"] <= GO_SVC else (JAVA if not (v["svcs"] & GO_SVC) else "both")
        who = {"generated": "secrets.sh generates it (kept in STATE_DIR/generated.env)", "third-party": "owner (secrets.local.env)", "fixed": "secrets.sh (fixed)", "empty": "owner, optional"}[v["kind"]]
        status = "ready" if v["kind"] in ("generated", "fixed") else ("MISSING until the owner provides it" if v["kind"] == "third-party" else "optional")
        req = "required" if v["kind"] in ("generated", "fixed") else ("see runbook" if v["kind"] == "third-party" else "optional")
        rows.append((k, d, req, "-", "Secret `%s` (SOPS, infra/ovh-vps/secrets.sh)" % ("afrotransact-go-secrets" if d == GO else "afrotransact-core-secrets" if d == JAVA else "both Secrets"), who, status))
    seen = {r[0] for r in rows}
    for name, env, dep in (("core", core, JAVA), ("go", go, GO)):
        for k, files in sorted(env.items()):
            val = files.get("values-prod.yaml") or files.get("values.yaml") or files.get("values-uat.yaml")
            rows.append((k, dep, "optional (has a value)", val, "Helm values (`extraEnv`, values.yaml / values-<env>.yaml)", "repo", "ready"))
    for k, e in sorted(reads.items()):
        if k in seen or k in core or k in go: continue
        if e["required"] and e["default"] is None:
            rows.append((k, JAVA, "required (no default in application-prod/uat)", "-", "UNKNOWN: not in secrets.sh, not in the chart (derived by the library chart if it is a URL / host)", "check", "VERIFY (library chart may derive it)"))
    lines = ["# Release 1 config inventory (generated)", "",
             "Generated by `python3 tools/release/config_inventory.py` from `infra/ovh-vps/secrets.sh`, the deployable charts and the modules' `application*.yml`. **Names only, never values.** Re-run after a config change; `--check` fails when this file is stale.",
             "UAT and PROD read the same names; they differ only by value (see `release-1-go-live.md`, section 3). Variables the library chart derives from `global.*Host` (`PLATFORM_DOMAIN`, `PUBLIC_WEB_URL`, `SELLER_CENTER_URL`, `STAFF_CONSOLE_URL`, `API_BASE_URL`, `AUTH_ISSUER_URL`, `MEDIA_PUBLIC_URL`, the upstream `*_URL` list) and `SPRING_PROFILES_ACTIVE` / `APP_ENV` (from `env:`) are set by Helm for every module.", "",
             "| Name | Deployable | Required | Default / value | Where set | Who provides it | Status |", "|---|---|---|---|---|---|---|"]
    for r in rows: lines.append("| " + " | ".join(str(c).replace("|", "/") for c in r) + " |")
    out = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == out else "config inventory is stale: run tools/release/config_inventory.py")
    OUT.write_text(out); print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} rows")
main()
