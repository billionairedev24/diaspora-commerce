#!/usr/bin/env python3
"""Keeps the NON-SECRET configuration of every module in the two deployable charts (release-1 parity, ADR 0011).

A service chart (java/services/<m>/deploy/helm, go/services/<m>/deploy/helm) carries a module's settings as `extraEnv` in values.yaml and
values-<env>.yaml (peer URLs such as GEO_URL, zones, TTLs, feature flags). The deployable chart (java/apps/core, go/apps/afrotransact-go)
runs ALL modules in one process, so it needs the union of those maps, or the module silently falls back to the localhost defaults of its
application.yml. This tool derives the union and keeps it in a GENERATED block inside `extraEnv:` of each deployable values file:

    extraEnv:
      # BEGIN module-env (generated by tools/release/chart_env_sync.py from the service charts; edit the service chart, then run it)
      GEO_URL: "http://geo:8080"
      # END module-env

  python3 tools/release/chart_env_sync.py            check: exit 1 when a deployable values file differs from what the service charts say
  python3 tools/release/chart_env_sync.py --write    rewrite the generated blocks
  python3 tools/release/chart_env_sync.py --json     machine-readable list of gaps (used by tools/release/parity.py)

Rules
  * values.yaml of a service -> values.yaml of the deployable; values-<env>.yaml -> the same file of the deployable, and only the keys whose
    value differs from the base union (the layering Helm applies is the same on both sides).
  * A name that two modules set to DIFFERENT values in the same file is a conflict: the tool refuses and prints both; resolve it by renaming
    one variable in the module (the module's application.yml owns the name) or by an explicit entry outside the generated block.
  * A name the deployable file already sets outside the block wins (never duplicated: a duplicate YAML key breaks Helm).
  * Names in tools/release/parity.yaml `config.env_skip` are never copied, each with the reason (database settings that core derives per
    module, the JVM flags, process-wide switches).
Secrets are not here: they are keys of afrotransact-<x>-secrets, rendered by infra/ovh-vps/secrets.sh (checked by parity.py `secrets`).
Standard library plus PyYAML.
"""
import argparse
import fnmatch
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
CONFIG = ROOT / "tools/release/parity.yaml"
PLAN = ROOT / "infra/argocd/launch-set/release-1.yaml"
SCOPES = ["values", "values-dev", "values-uat", "values-prod", "values-trial"]
BEGIN = "  # BEGIN module-env (generated by tools/release/chart_env_sync.py from the service charts; edit the service chart, then run it)"
END = "  # END module-env"
BLOCK_RE = re.compile(r"^  # BEGIN module-env.*?\n(?:.*\n)*?  # END module-env\n", re.M)


def load_yaml(path):
    try:
        return yaml.safe_load(path.read_text()) or {}
    except FileNotFoundError:
        return {}


def skip_rules():
    cfg = load_yaml(CONFIG)
    return (cfg.get("config") or {}).get("env_skip") or {}


def skipped(name, rules):
    return any(fnmatch.fnmatch(name, pattern) for pattern in rules)


def deployables(root=ROOT):
    plan = load_yaml(root / "infra/argocd/launch-set/release-1.yaml")
    for dep, spec in (plan.get("deployables") or {}).items():
        yield dep, spec["runtime"], root / spec["chart"], list(spec["modules"])


def union(root, runtime, modules, scope, rules):
    """name -> {module: value} for one scope, skipping the names in env_skip."""
    out = {}
    for m in modules:
        chart = root / f"{runtime}/services/{m}/deploy/helm"
        for k, v in (load_yaml(chart / f"{scope}.yaml").get("extraEnv") or {}).items():
            if not skipped(k, rules):
                out.setdefault(k, {})[m] = "" if v is None else str(v)
    return out


def render_block(entries):
    lines = [BEGIN] + [f"  {k}: {json.dumps(v)}" for k, v in sorted(entries.items())] + [END]
    return "\n".join(lines) + "\n"


def apply_block(text, entries):
    """Return `text` with the generated block replaced, inserted after `extraEnv:`, or appended with a new `extraEnv:`."""
    text = BLOCK_RE.sub("", text)
    block = render_block(entries) if entries else ""
    if not entries:
        return text
    if re.search(r"^extraEnv:\s*\{\}\s*(#.*)?$", text, re.M):
        return re.sub(r"^extraEnv:\s*\{\}\s*(#.*)?$", lambda _m: "extraEnv:\n" + block.rstrip("\n"), text, count=1, flags=re.M)
    m = re.search(r"^extraEnv:\s*(#.*)?\n", text, re.M)
    if m:
        # the end of the mapping: the next top-level key, minus the comment lines that belong to that key
        lines = text.splitlines(keepends=True)
        start = text[: m.end()].count("\n")
        end = start
        while end < len(lines) and not (re.match(r"\S", lines[end]) and not lines[end].startswith("#")):
            end += 1
        while end > start and (lines[end - 1].strip() == "" or lines[end - 1].startswith("#")):
            end -= 1
        return "".join(lines[:end]) + block + "".join(lines[end:])
    if not text.endswith("\n"):
        text += "\n"
    return text + "extraEnv:\n" + block


def plan(root=ROOT):
    """Yield (deployable, file, wanted_text, current_text, conflicts, kept) for every deployable values file."""
    rules = skip_rules()
    for dep, runtime, chart, modules in deployables(root):
        base = union(root, runtime, modules, "values", rules)
        for scope in SCOPES:
            path = chart / f"{scope}.yaml"
            if not path.exists():
                continue
            current = path.read_text()
            scoped = union(root, runtime, modules, scope, rules)
            conflicts = {k: v for k, v in scoped.items() if len(set(v.values())) > 1}
            entries = {}
            for k, v in scoped.items():
                if k in conflicts:
                    continue
                value = next(iter(v.values()))
                base_value = next(iter(base[k].values())) if k in base and len(set(base[k].values())) == 1 else None
                if scope == "values" or value != base_value:
                    entries[k] = value
            # names set by hand outside the block win and are not repeated inside it
            outside = BLOCK_RE.sub("", current)
            manual = set(((yaml.safe_load(outside) or {}).get("extraEnv") or {}).keys())
            kept = sorted(k for k in entries if k in manual)
            entries = {k: v for k, v in entries.items() if k not in manual}
            yield dep, path, apply_block(current, entries), current, conflicts, kept


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()
    gaps, bad = [], 0
    for dep, path, wanted, current, conflicts, kept in plan():
        rel = path.relative_to(ROOT).as_posix()
        for k, v in sorted(conflicts.items()):
            bad += 1
            gaps.append({"file": rel, "name": k, "problem": "conflict", "detail": v})
            if not args.json:
                print(f"CONFLICT {rel}: {k} is set to different values by {v}")
        if wanted != current:
            if args.write:
                path.write_text(wanted)
                print(f"wrote {rel}")
            else:
                missing = sorted(set(re.findall(r"^  ([A-Z][A-Z0-9_]*): ", wanted, re.M)) - set(re.findall(r"^  ([A-Z][A-Z0-9_]*): ", current, re.M)))
                bad += 1
                gaps.append({"file": rel, "name": ", ".join(missing) or "(block out of date)", "problem": "out-of-date"})
                if not args.json:
                    print(f"OUT OF DATE {rel}: {', '.join(missing) if missing else 'generated block differs'}")
    if args.json:
        print(json.dumps(gaps))
    elif not args.write:
        print("chart env sync: " + ("FAILED (run: python3 tools/release/chart_env_sync.py --write)" if bad else "OK"))
    return 1 if (bad and not args.write) else (1 if any(g["problem"] == "conflict" for g in gaps) else 0)


if __name__ == "__main__":
    sys.exit(main())
